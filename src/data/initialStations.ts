// Helper to filter disasters for a given station
function getDisastersForStation(state: string, placeKeywords: string[]) {
  return NORTHEAST_NATURAL_DISASTERS.filter((d) => {
    if (d.state.toLowerCase().includes(state.toLowerCase())) {
      return true;
    }
    return placeKeywords.some(
      (kw) =>
        d.location.toLowerCase().includes(kw.toLowerCase()) ||
        d.eventTitle.toLowerCase().includes(kw.toLowerCase())
    );
  });
}

